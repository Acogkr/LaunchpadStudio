#!/usr/bin/env python3
"""Validate and compile the UTF-8 translation catalog into standard .lproj bundles."""
import argparse, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
LANGUAGES = ('en', 'ko', 'ja', 'zh-Hans')

def validate(catalog):
    assert set(catalog) == set(LANGUAGES), 'Exactly four languages are required'
    keys = set(catalog['en'])
    for code in LANGUAGES:
        assert set(catalog[code]) == keys, f'{code}: missing/extra translation keys'
        for key, text in catalog[code].items():
            assert isinstance(text, str) and text.strip(), f'{code}: empty {key}'
            assert sorted(re.findall(r'\{\d+\}', key)) == sorted(re.findall(r'\{\d+\}', text)), f'{code}: placeholder mismatch: {key}'
            assert '\\(' not in text, f'{code}: unconverted Swift interpolation'
    # Every literal lookup must have a translation. A few keys are resolved dynamically
    # (backup reasons and classification labels), so extra resource keys are allowed.
    for source in (ROOT/'Sources').rglob('*.swift'):
        for match in re.finditer(r'\bL\(\s*("(?:\\.|[^"\\])*")', source.read_text()):
            key = json.loads(match[1])
            assert key in keys, f'{source.relative_to(ROOT)}: unknown key {key}'
    return len(keys)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=pathlib.Path, default=ROOT/'Resources')
    args = parser.parse_args()
    catalog = json.loads((ROOT/'Resources/Translations.json').read_text())
    count = validate(catalog)
    if not args.check:
        for code in LANGUAGES:
            folder = args.output/(code+'.lproj'); folder.mkdir(parents=True, exist_ok=True)
            lines = ['/* Generated by Scripts/localizations.py. Edit Translations.json instead. */']
            lines += [json.dumps(k,ensure_ascii=False)+' = '+json.dumps(v,ensure_ascii=False)+';' for k,v in sorted(catalog[code].items())]
            (folder/'Localizable.strings').write_text('\n'.join(lines)+'\n')
            privacy = {
                'NSAppleEventsUsageDescription': 'Use Finder to move selected files to Trash, restore them, or empty Trash when you request it.',
                'NSAppBundlesUsageDescription': 'Move the apps you select to Trash.',
                'NSAppDataUsageDescription': 'Find related files for the app you selected and move only the files you choose to Trash.',
            }
            (folder/'InfoPlist.strings').write_text('\n'.join(
                json.dumps(key)+' = '+json.dumps(catalog[code][value], ensure_ascii=False)+';'
                for key, value in privacy.items())+'\n')
    print(f'Localization validation passed: {count} keys × {len(LANGUAGES)} languages')

if __name__ == '__main__': main()
